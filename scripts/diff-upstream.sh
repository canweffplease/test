#!/usr/bin/env bash
# Regenerate the complete diff of our vendored HTSIM against pristine upstream.
# Run this after any change to HTSIM/ so the record stays current.
#
#   ./scripts/diff-upstream.sh
#
# Writes docs/htsim-changes-vs-upstream.patch (apply to upstream with -p1)
# and rewrites docs/HTSIM_UPSTREAM_COMMIT.txt with the full pinned hash.
# Needs network access to github.com.
#
# Only files git tracks under HTSIM/ are compared (working-tree contents, so
# uncommitted edits to tracked files are included). Build directories
# (build, build_*), binaries and run artifacts (logout.dat, idmap.txt) are
# ignored by git and therefore stay out of the patch. Our OUR_CHANGES*.md
# notes are excluded too.
set -euo pipefail
export LC_ALL=C   # sort and comm must agree on collation
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PINNED=$(tr -d '[:space:]' < "$HERE/docs/HTSIM_UPSTREAM_COMMIT.txt")
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

echo "cloning pristine upstream at $PINNED ..."
git clone --quiet https://github.com/spcl/HTSIM.git "$TMP/a"
git -C "$TMP/a" checkout --quiet "$PINNED"
FULL=$(git -C "$TMP/a" rev-parse HEAD)
rm -rf "$TMP/a/.git"

echo "copying our tracked HTSIM files ..."
mkdir -p "$TMP/ours"
(cd "$HERE" && git ls-files -z -- HTSIM | xargs -0 cp --parents -t "$TMP/ours")
mv "$TMP/ours/HTSIM" "$TMP/b"

# Upstream files we pruned (Dragonfly/SlimFly artifacts, sample outputs) are
# listed in the patch header, not diffed as deletions. Files we added are
# diffed in full (-N), so the patch recreates them.
PATCH="$HERE/docs/htsim-changes-vs-upstream.patch"
(cd "$TMP/a" && find . -type f | sed 's|^\./||' | sort) > "$TMP/up.lst"
(cd "$TMP/b" && find . -type f | sed 's|^\./||' | sort) > "$TMP/our.lst"
comm -23 "$TMP/up.lst" "$TMP/our.lst" > "$TMP/pruned.lst"
{
  echo "HTSIM changes vs upstream https://github.com/spcl/HTSIM at $FULL"
  echo "Generated by scripts/diff-upstream.sh. Apply in an upstream checkout with patch -p1."
  echo
  echo "Upstream files removed in our copy (pruned, not part of the patch): $(wc -l < "$TMP/pruned.lst")"
  awk -F/ '{d=$1; for(i=2;i<NF;i++) d=d"/"$i; print "  " d "/"}' "$TMP/pruned.lst" | sort | uniq -c
  echo
} > "$PATCH"
(cd "$TMP/a" && xargs -d '\n' rm -f < "$TMP/pruned.lst")
(cd "$TMP" && diff -ruN --exclude='OUR_CHANGES*.md' a b >> "$PATCH") || true
echo "$FULL" > "$HERE/docs/HTSIM_UPSTREAM_COMMIT.txt"

echo
echo "files we changed (upstream $FULL):"
grep "^diff -ruN" "$PATCH" | awk '{print "  " $NF}' | sed 's|^  b/|  |'
echo
echo "wrote docs/htsim-changes-vs-upstream.patch ($(wc -c < "$PATCH") bytes)"
